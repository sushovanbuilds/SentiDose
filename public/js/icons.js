/**
 * Build an inline SVG string for a named icon.
 * @param {string} name key in ICONS
 * @param {{size?: number, label?: string}} [options]
 * @returns {string} SVG markup
 */
function icon(name, options = {}) {
  const body = ICONS[name];
  if (!body) throw new Error(`Unknown icon: ${name}`);
  const size = options.size || 24;
  const label = options.label;
  const a11y = label
    ? `role="img" aria-label="${label}"`
    : 'aria-hidden="true" focusable="false"';
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" ${a11y}>${body}</svg>`;
}

/**
 * Replace every <span data-icon="name"> in the document with its SVG.
 * @param {Document} [root]
 */
function hydrateIcons(root = document) {
  root.querySelectorAll('[data-icon]').forEach((element) => {
    const name = element.getAttribute('data-icon');
    if (!ICONS[name]) return;
    element.innerHTML = icon(name, {
      size: Number(element.dataset.size) || 24,
      label: element.dataset.label || undefined,
    });
  });
}

